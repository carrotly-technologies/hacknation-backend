import { Test, TestingModule } from '@nestjs/testing';
import { INestApplication } from '@nestjs/common';
import request from 'supertest';
import { App } from 'supertest/types.js';
import { AppModule } from './../src/app.module.js';
import { configureApp, DEFAULT_FRONTEND_URL } from './../src/configure-app.js';

describe('Health (e2e)', () => {
  let app: INestApplication<App>;

  beforeEach(async () => {
    const moduleFixture: TestingModule = await Test.createTestingModule({
      imports: [AppModule],
    }).compile();

    app = moduleFixture.createNestApplication();
    configureApp(app);
    await app.init();
  });

  afterEach(async () => {
    await app.close();
  });

  it('GET /api/health returns {"status":"ok"}', () => {
    return request(app.getHttpServer())
      .get('/api/health')
      .expect(200)
      .expect({ status: 'ok' });
  });

  it('allows CORS from the frontend origin', () => {
    return request(app.getHttpServer())
      .get('/api/health')
      .set('Origin', DEFAULT_FRONTEND_URL)
      .expect('Access-Control-Allow-Origin', DEFAULT_FRONTEND_URL);
  });
});
