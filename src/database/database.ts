import { join } from 'node:path';
import type { PgAsyncDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';

/**
 * Any PostgreSQL Drizzle database: node-postgres in the app, PGlite in tests.
 * Repositories depend on this type, not on a driver.
 */
// oxlint-disable-next-line no-explicit-any -- relations differ per driver
export type Database = PgAsyncDatabase<PgQueryResultHKT, any>;

/**
 * Injection token of the database, or `null` when DATABASE_URL is not set.
 * Feature modules pick their in-memory storage on `null`.
 */
export const DATABASE = Symbol('DATABASE');

/** Migrations generated by drizzle-kit (`drizzle/` at the repo root). */
export const MIGRATIONS_FOLDER = join(
  import.meta.dirname,
  '..',
  '..',
  'drizzle',
);
